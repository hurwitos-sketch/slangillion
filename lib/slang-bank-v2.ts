export const SLANG_BANK: SlangEntry[] = Object.entries(groups).flatMap(
  ([question, tiers]) =>
    tiers.flatMap(([tier, explanation, rows]) =>
      rows.map((row) => {
        const [canonical, ...aliases] = row.split("|");
        const [reviewedTier, reviewedExplanation] = scoreReviews[
          `${question}:${canonical}`
        ] ?? [tier, explanation];
        return {
          question,
          canonical,
          tier: reviewedTier,
          points: points[reviewedTier - 1],
          aliases: aliases.filter(
            (alias, i) =>
              normalize(alias) !== normalize(canonical) &&
              aliases.findIndex(
                (other) => normalize(other) === normalize(alias),
              ) === i,
          ),
          explanation: reviewedExplanation,
          reviewStatus: "editorially-reviewed" as const,
        };
      }),
    ),
);
